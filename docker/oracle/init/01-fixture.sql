-- Fixture warehouse for @dash/adapter-oracle.
-- The image runs this file after the database is open. SQL*Plus connects as SYS,
-- so the script enters FREEPDB1 and creates the application schema itself.

WHENEVER SQLERROR EXIT SQL.SQLCODE

ALTER SESSION SET CONTAINER = FREEPDB1;

ALTER PROFILE DEFAULT LIMIT
  PASSWORD_VERIFY_FUNCTION NULL
  PASSWORD_LIFE_TIME UNLIMITED
  FAILED_LOGIN_ATTEMPTS UNLIMITED;

DECLARE
  name_in_use EXCEPTION;
  PRAGMA EXCEPTION_INIT(name_in_use, -1920);
BEGIN
  EXECUTE IMMEDIATE 'CREATE USER DASH IDENTIFIED BY "Dash_test1" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS';
EXCEPTION
  WHEN name_in_use THEN
    NULL;
END;
/

GRANT DB_DEVELOPER_ROLE TO DASH;
ALTER USER DASH QUOTA UNLIMITED ON USERS ACCOUNT UNLOCK;

DECLARE
  name_in_use EXCEPTION;
  PRAGMA EXCEPTION_INIT(name_in_use, -955);
BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE DASH.ORDERS (
      ID NUMBER(10) NOT NULL PRIMARY KEY,
      TOTAL NUMBER(10) NOT NULL,
      STATUS VARCHAR2(32) NOT NULL,
      REGION VARCHAR2(64),
      NOTE CLOB
    )';
EXCEPTION
  WHEN name_in_use THEN
    NULL;
END;
/

DECLARE
  name_in_use EXCEPTION;
  PRAGMA EXCEPTION_INIT(name_in_use, -955);
BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE DASH.REVENUE (
      MONTH VARCHAR2(16) NOT NULL PRIMARY KEY,
      AMOUNT NUMBER(10) NOT NULL
    )';
EXCEPTION
  WHEN name_in_use THEN
    NULL;
END;
/

DECLARE
  name_in_use EXCEPTION;
  PRAGMA EXCEPTION_INIT(name_in_use, -955);
BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE DASH.METRICS (
      ID NUMBER(10) NOT NULL PRIMARY KEY,
      BILLED_ON DATE NOT NULL,
      AMOUNT NUMBER(38) NOT NULL
    )';
EXCEPTION
  WHEN name_in_use THEN
    NULL;
END;
/

INSERT INTO DASH.ORDERS (ID, TOTAL, STATUS, REGION, NOTE)
SELECT 1, 10, 'paid', 'Europe', 'first' FROM dual
WHERE NOT EXISTS (SELECT 1 FROM DASH.ORDERS)
UNION ALL
SELECT 2, 25, 'paid', 'Europe', NULL FROM dual
WHERE NOT EXISTS (SELECT 1 FROM DASH.ORDERS)
UNION ALL
SELECT 3, 5, 'open', 'Asia Pacific', 'third' FROM dual
WHERE NOT EXISTS (SELECT 1 FROM DASH.ORDERS)
UNION ALL
SELECT 4, 40, 'paid', 'North America', NULL FROM dual
WHERE NOT EXISTS (SELECT 1 FROM DASH.ORDERS)
UNION ALL
SELECT 5, 15, 'Paid', 'Europe', NULL FROM dual
WHERE NOT EXISTS (SELECT 1 FROM DASH.ORDERS);

INSERT INTO DASH.REVENUE (MONTH, AMOUNT)
SELECT '2026-01', 10 FROM dual
WHERE NOT EXISTS (SELECT 1 FROM DASH.REVENUE)
UNION ALL
SELECT '2026-02', 20 FROM dual
WHERE NOT EXISTS (SELECT 1 FROM DASH.REVENUE)
UNION ALL
SELECT '2026-03', 15 FROM dual
WHERE NOT EXISTS (SELECT 1 FROM DASH.REVENUE);

INSERT INTO DASH.METRICS (ID, BILLED_ON, AMOUNT)
SELECT 1, DATE '2026-01-15', 9007199254740993 FROM dual
WHERE NOT EXISTS (SELECT 1 FROM DASH.METRICS);

CREATE OR REPLACE VIEW DASH.PAID_ORDERS AS
SELECT ID, TOTAL, STATUS, REGION
FROM DASH.ORDERS
WHERE STATUS = 'paid';

EXIT
